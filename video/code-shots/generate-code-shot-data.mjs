#!/usr/bin/env node

import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { codeShotConfig } from "./code-shot-config.mjs";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const showcaseRoot = resolve(scriptDirectory, "../..");
const dataPath = resolve(scriptDirectory, "code-shot-data.js");
const manifestPath = resolve(scriptDirectory, "code-shot-manifest.md");
const MASTER_HANDOFF_MS = 140;

function formatRange(start, end) {
  return start === end ? String(start) : `${start}–${end}`;
}

function formatRanges(segments) {
  return segments
    .map((segment) => `${segment.source}:${formatRange(segment.start, segment.end)}`)
    .join("; ");
}

function formatDuration(milliseconds) {
  return `${(milliseconds / 1000).toFixed(2)} seconds`;
}

function escapeMarkdown(value) {
  return String(value).replaceAll("|", "\\|");
}

async function loadSegment(segment) {
  const sourcePath = resolve(showcaseRoot, segment.source);
  const sourceText = await readFile(sourcePath, "utf8");
  const sourceLines = sourceText.split(/\r?\n/);

  assert.ok(segment.start >= 1, `${segment.source} starts before line 1`);
  assert.ok(segment.end >= segment.start, `${segment.source} has an invalid line range`);
  assert.ok(segment.end <= sourceLines.length, `${segment.source} ends after its final line`);
  assert.ok(segment.phases.length > 0, `${segment.source} has no animation phases`);

  const lineNumbers = new Set(
    Array.from({ length: segment.end - segment.start + 1 }, (_, index) => segment.start + index),
  );
  for (const phase of segment.phases) {
    assert.ok(phase.durationMs > 0, `${segment.source} has a non-positive phase duration`);
    for (const line of phase.lines) {
      assert.ok(lineNumbers.has(line), `${segment.source}:${line} is outside its segment`);
    }
  }

  const lines = sourceLines.slice(segment.start - 1, segment.end).map((text, index) => ({
    number: segment.start + index,
    text,
  }));
  return {
    source: segment.source,
    sourceContent: lines.map((line) => line.text).join("\n"),
    start: segment.start,
    end: segment.end,
    lineCount: lines.length,
    lines,
    phases: segment.phases,
    durationMs: segment.phases.reduce((total, phase) => total + phase.durationMs, 0),
  };
}

async function buildPayload() {
  assert.equal(codeShotConfig.length, 10, "The code-shot manifest must contain ten tasks");
  assert.deepEqual(
    codeShotConfig.map((shot) => shot.task),
    Array.from({ length: 10 }, (_, index) => index + 1),
    "Tasks must be numbered 1–10 in order",
  );

  const shots = [];
  for (const shot of codeShotConfig) {
    const segments = [];
    for (const segment of shot.segments) segments.push(await loadSegment(segment));
    shots.push({
      task: shot.task,
      label: `TASK ${String(shot.task).padStart(2, "0")} · ${shot.title}`,
      title: shot.title,
      description: shot.description,
      functions: shot.functions,
      priority: shot.priority,
      recommendation: shot.recommendation,
      recommendationReason: shot.recommendationReason,
      segments,
      durationMs: segments.reduce((total, segment) => total + segment.durationMs, 0),
    });
  }

  return {
    generatedFrom: "code-shot-config.mjs",
    shots,
  };
}

function renderDataFile(payload) {
  return `// Generated by generate-code-shot-data.mjs. Do not edit by hand.\nwindow.CODE_SHOTS = ${JSON.stringify(payload, null, 2)};\n`;
}

function renderManifest(payload) {
  const showCodeShots = payload.shots.filter((shot) => shot.recommendation === "SHOW CODE");
  const showCodeDuration = showCodeShots.reduce((total, shot) => total + shot.durationMs, 0);
  const masterDuration = payload.shots.reduce((total, shot) => total + shot.durationMs, 0)
    + Math.max(0, payload.shots.length - 1) * MASTER_HANDOFF_MS;
  const lines = [
    "# BPhO 2026 code-shot manifest",
    "",
    "Generated from `code-shot-config.mjs` and the live source files. The filming page reads `code-shot-data.js`; regenerate it after any source-line change with:",
    "",
    "```bash",
    "node video/code-shots/generate-code-shot-data.mjs",
    "```",
    "",
    "Every displayed line below is extracted verbatim from the named source range. The source ranges are intentionally compact; the animation phases only change the highlight and viewport position.",
    "",
  ];

  for (const shot of payload.shots) {
    lines.push(`## Task ${String(shot.task).padStart(2, "0")} — ${shot.title.toLowerCase()}`);
    lines.push("");
    lines.push(`- **Priority:** ${shot.priority}`);
    lines.push(`- **Exact source file(s):** ${shot.segments.map((segment) => `\`${segment.source}\``).filter((source, index, all) => all.indexOf(source) === index).join(", ")}`);
    lines.push(`- **Exact function name(s):** ${shot.functions.map((name) => `\`${name}()\``).join(", ")}`);
    lines.push(`- **Exact line range(s):** ${formatRanges(shot.segments)}`);
    lines.push(`- **What it computes:** ${shot.description}`);
    lines.push(`- **Suggested duration:** ${formatDuration(shot.durationMs)}`);
    lines.push(`- **Recommended final usage:** ${shot.recommendation === "SHOW CODE" ? `SHOW CODE — ${(shot.durationMs / 1000).toFixed(2)} seconds` : "SKIP CODE — website equation/result is stronger"}`);
    lines.push(`- **Why:** ${shot.recommendationReason}`);
    lines.push("");
    lines.push("| Source range | Highlight progression |");
    lines.push("| --- | --- |");
    for (const segment of shot.segments) {
      const phaseText = segment.phases
        .map((phase) => `${phase.lines.join(", ")} — ${phase.caption}`)
        .join(" → ");
      lines.push(`| ${escapeMarkdown(`${segment.source}:${formatRange(segment.start, segment.end)}`)} | ${escapeMarkdown(phaseText)} |`);
    }
    lines.push("");
  }

  lines.push("## Recommended final screencast usage");
  lines.push("");
  lines.push(`The complete master sequence is approximately **${(masterDuration / 1000).toFixed(2)} seconds**. For the final ≤3-minute BPhO screencast, use only the highest-signal code evidence below: **${(showCodeDuration / 1000).toFixed(2)} seconds total**.`);
  lines.push("");
  for (const shot of payload.shots) {
    lines.push(`- Task ${shot.task}: ${shot.recommendation === "SHOW CODE" ? `SHOW CODE — ${(shot.durationMs / 1000).toFixed(2)} seconds` : "SKIP CODE — website equation/result is stronger"}`);
  }
  lines.push("");
  lines.push("Tasks 1, 2, 6, 7, 8, 9, and 10 are the recommended dedicated code inserts. Tasks 3–5 remain available as individual scenes if the edit needs extra implementation evidence.");
  return `${lines.join("\n")}\n`;
}

const payload = await buildPayload();
await writeFile(dataPath, renderDataFile(payload));
await writeFile(manifestPath, renderManifest(payload));

const relativeDataPath = relative(process.cwd(), dataPath);
const relativeManifestPath = relative(process.cwd(), manifestPath);
console.log(`Generated ${relativeDataPath} and ${relativeManifestPath}`);
const masterDuration = payload.shots.reduce((total, shot) => total + shot.durationMs, 0)
  + Math.max(0, payload.shots.length - 1) * MASTER_HANDOFF_MS;
console.log(`Master sequence: ${(masterDuration / 1000).toFixed(2)} seconds including ${MASTER_HANDOFF_MS} ms task handoffs`);
console.log(`Recommended code inserts: ${(payload.shots.filter((shot) => shot.recommendation === "SHOW CODE").reduce((total, shot) => total + shot.durationMs, 0) / 1000).toFixed(2)} seconds`);
for (const shot of payload.shots) {
  console.log(`Task ${String(shot.task).padStart(2, "0")}: ${formatDuration(shot.durationMs)} · ${formatRanges(shot.segments)}`);
}
